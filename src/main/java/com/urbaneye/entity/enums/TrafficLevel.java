package com.urbaneye.entity.enums;

/**
 * Traffic congestion levels for urban road segments.
 *
 * LOW      — 0% to 25% congestion (Green)
 * MODERATE — 25% to 50% congestion (Yellow)
 * HIGH     — 50% to 75% congestion (Orange)
 * SEVERE   — 75% to 100% congestion (Red)
 */
public enum TrafficLevel {
    LOW,
    MODERATE,
    HIGH,
    SEVERE
}
